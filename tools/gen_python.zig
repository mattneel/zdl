const std = @import("std");
const zdl = @import("zdl");
const schemas = zdl.interop.schemas;
const c_header = zdl.codegen.c_header;

pub fn main() !void {
    var gpa = std.heap.GeneralPurposeAllocator(.{}){};
    defer _ = gpa.deinit();
    const allocator = gpa.allocator();

    const args = try std.process.argsAlloc(allocator);
    defer std.process.argsFree(allocator, args);

    if (args.len < 2) {
        std.debug.print("usage: gen_python <output_dir>\n", .{});
        return error.InvalidArgs;
    }

    const output_dir_path = args[1];
    var dir = try std.fs.cwd().makeOpenPath(output_dir_path, .{});
    defer dir.close();

    // Generate the main zdl.py module
    {
        var file = try dir.createFile("zdl.py", .{ .truncate = true });
        defer file.close();

        var list = std.ArrayListUnmanaged(u8){};
        defer list.deinit(allocator);

        try generatePythonModule(list.writer(allocator));
        try file.writeAll(list.items);

        std.debug.print("generated zdl.py\n", .{});
    }
}

