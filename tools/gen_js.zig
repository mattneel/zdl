        \\export declare function loadZdl(
        \\  source: BufferSource | WebAssembly.Module | Response | Promise<Response>,
        \\): Promise<ZdlApi>;
        \\
    );
}

fn generateSchemaDts(comptime T: type, writer: anytype) !void {
    const type_name = c_header.simplifyTypeName(@typeName(T));

    // decoded + init interfaces for T and every nested struct
    const struct_types = comptime collectStructs(T, &[_]type{});
    inline for (struct_types) |S| {
        try emitStructInterfaces(S, writer);
    }

    // filterable fields: numeric (int/float) fields only, per the query module
    try writer.print("export type {s}FilterField =", .{type_name});
    comptime var any_filterable = false;
    inline for (std.meta.fields(T)) |field| {
        if (field.is_comptime) continue;
        switch (@typeInfo(field.type)) {
            .int, .float => {
                try writer.print("\n  | \"{s}\"", .{field.name});
                any_filterable = true;
            },
            else => {},
        }
    }
    if (!any_filterable) try writer.writeAll(" never");
    try writer.writeAll(";\n\n");

    try writer.print(
        \\export interface {s}Static {{
        \\  structSize(): number;
        \\  fieldCount(): number;
        \\  serializedSize(target?: TargetValue): number;
        \\  serialize(obj: {s}Init, target?: TargetValue): Uint8Array;
        \\  deserialize(data: ByteSource): {s};
        \\  serializeArray(items: readonly {s}Init[], target?: TargetValue): Uint8Array;
        \\  arrayCount(data: ByteSource): number;
        \\}}
        \\
        \\export interface {s}Query extends Iterable<{s}> {{
        \\  filter(field: {s}FilterField, op: CompareOp, value: number | bigint | boolean): this;
        \\  limit(n: number): this;
        \\  offset(n: number): this;
        \\  collect(): {s}[];
        \\  count(): number;
        \\  reset(): void;
        \\  free(): void;
        \\}}
        \\
        \\export interface {s}QueryConstructor {{
        \\  new (data: ByteSource): {s}Query;
        \\}}
        \\
        \\export interface {s}Mutable extends Iterable<{s}> {{
        \\  /** Append a record; returns its slot. Throws CAPACITY_FULL when out
        \\   *  of room (call reserve() first). */
        \\  append(obj: {s}Init): number;
        \\  /** Read the record at slot (decoded copy). */
        \\  get(slot: number): {s};
        \\  /** Integrity-checked read: verifies the record CRC (decoded copy). */
        \\  getVerified(slot: number): {s};
        \\  /** In-place update; re-CRCs exactly one record. */
        \\  update(slot: number, obj: {s}Init): void;
        \\  /** Tombstone delete: no bytes move; compact() reclaims. */
        \\  delete(slot: number): void;
        \\  /** Reclaim tombstones (relocation fence; order preserved). */
        \\  compact(): void;
        \\  /** Grow capacity (relocation fence; failure-atomic). */
        \\  reserve(additional: number): void;
        \\  /** Live (non-deleted) record count. */
        \\  readonly live: number;
        \\  /** Slots in use, including tombstoned ones. */
        \\  readonly slots: number;
        \\  /** Bumped whenever a fence (compact/reserve) relocates storage. */
        \\  readonly generation: bigint;
        \\  /** Serialize live records to an array container. */
        \\  flush(): Uint8Array;
        \\  free(): void;
        \\}}
        \\
        \\export interface {s}MutableConstructor {{
        \\  new (capacity?: number): {s}Mutable;
        \\  /** Load a serialized array container (validates container CRC). */
        \\  load(data: ByteSource, extraCapacity?: number): {s}Mutable;
        \\}}
        \\
        \\
    , .{
        type_name, type_name, type_name, type_name,
        type_name, type_name, type_name, type_name,
        type_name, type_name, type_name, type_name,
        type_name, type_name, type_name, type_name,
        type_name, type_name, type_name,
    });
}

fn emitStructInterfaces(comptime S: type, writer: anytype) !void {
    const name = c_header.simplifyTypeName(@typeName(S));

    // decoded shape (what reads return)
    try writer.print("export interface {s} {{\n", .{name});
    inline for (std.meta.fields(S)) |field| {
        if (field.is_comptime) continue;
        try writer.print("  {s}: {s};\n", .{ field.name, comptime tsDecodedType(field.type) });
    }
    try writer.writeAll("}\n\n");

    // init shape (what encodes accept; every field optional, zero-defaulted)
    try writer.print("export interface {s}Init {{\n", .{name});
    inline for (std.meta.fields(S)) |field| {
        if (field.is_comptime) continue;
        try writer.print("  {s}?: {s};\n", .{ field.name, comptime tsInitType(field.type) });
    }
    try writer.writeAll("}\n\n");
}

fn tsDecodedType(comptime F: type) []const u8 {
    return switch (@typeInfo(F)) {
        .bool => "boolean",
        .int => |info| if (info.bits == 64) "bigint" else "number",
        .float => "number",
        .array => |info| blk: {
            if (info.child == u8) break :blk "Uint8Array";
            break :blk switch (@typeInfo(info.child)) {
                .bool => "boolean[]",
                .int => |child| if (child.bits == 64) "bigint[]" else "number[]",
                .float => "number[]",
                .@"struct" => std.fmt.comptimePrint("{s}[]", .{c_header.simplifyTypeName(@typeName(info.child))}),
                else => @compileError("Unsupported array element type for TypeScript declarations"),
            };
        },
        .@"struct" => c_header.simplifyTypeName(@typeName(F)),
        else => @compileError("Unsupported field type for TypeScript declarations"),
    };
}

fn tsInitType(comptime F: type) []const u8 {
    return switch (@typeInfo(F)) {
        .bool => "boolean",
        .int => |info| if (info.bits == 64) "bigint | number" else "number",
        .float => "number",
        .array => |info| blk: {
            if (info.child == u8) break :blk "string | Uint8Array | ArrayLike<number>";
            break :blk switch (@typeInfo(info.child)) {
                .bool => "ArrayLike<boolean>",
                .int => |child| if (child.bits == 64) "ArrayLike<bigint | number>" else "ArrayLike<number>",
                .float => "ArrayLike<number>",
                .@"struct" => std.fmt.comptimePrint("readonly {s}Init[]", .{c_header.simplifyTypeName(@typeName(info.child))}),
                else => @compileError("Unsupported array element type for TypeScript declarations"),
            };
        },
        .@"struct" => std.fmt.comptimePrint("{s}Init", .{c_header.simplifyTypeName(@typeName(F))}),
        else => @compileError("Unsupported field type for TypeScript declarations"),
    };
}
