    try writer.writeAll(
        \\// zdl - TypeScript declarations for zdl.mjs (wasm64-freestanding)
        \\// Auto-generated by zdl - do not edit manually.
        \\
        \\export declare const Target: Readonly<{ CPU: 0; DISK: 1; NETWORK: 2 }>;
        \\export type TargetValue = 0 | 1 | 2;
        \\
        \\export declare const Comparison: Readonly<{ EQ: 0; NE: 1; LT: 2; LE: 3; GT: 4; GE: 5 }>;
        \\export type CompareOp =
        \\  | 0 | 1 | 2 | 3 | 4 | 5
        \\  | "==" | "=" | "eq"
        \\  | "!=" | "<>" | "ne"
        \\  | "<" | "lt"
        \\  | "<=" | "le"
        \\  | ">" | "gt"
        \\  | ">=" | "ge";
        \\
        \\export declare const ZdlError: Readonly<{
        \\  OK: 0; NULL_PARAM: 1; INVALID_FIELD: 2; TYPE_MISMATCH: 3;
        \\  BUFFER_CORRUPT: 4; OUT_OF_MEMORY: 5; LIMIT_EXCEEDED: 6;
        \\  LIMIT_REQUIRED: 7; TOO_MANY_FILTERS: 8; ITERATOR_NOT_STARTED: 9;
        \\  UNSUPPORTED_TYPE: 10; CAPACITY_FULL: 11; STALE_VIEW: 12;
        \\  SLOT_OUT_OF_RANGE: 13; SLOT_DELETED: 14; CHECKSUM_MISMATCH: 15;
        \\  VERSION_MISMATCH: 16; BUFFER_TOO_SMALL: 17; DATA_TOO_LARGE: 18;
        \\}>;
        \\
        \\export declare class ZdlException extends Error {
        \\  readonly code: number;
        \\  constructor(code: number, message: string);
        \\}
        \\
        \\/** Bytes accepted wherever serialized data is consumed. */
        \\export type ByteSource = Uint8Array | ArrayLike<number>;
        \\
        \\
    );

    inline for (schemas.registry) |entry| {
        try generateSchemaDts(entry.Type, writer);
    }

    // The bound API returned by loadZdl
    try writer.writeAll("/** API bound to one instantiated zdl wasm module. */\nexport interface ZdlApi {\n");
    try writer.writeAll("  instance: WebAssembly.Instance;\n");
    try writer.writeAll("  Target: typeof Target;\n  Comparison: typeof Comparison;\n  ZdlError: typeof ZdlError;\n");
    inline for (schemas.registry) |entry| {
        const type_name = c_header.simplifyTypeName(@typeName(entry.Type));
        try writer.print("  {s}: {s}Static;\n  {s}Query: {s}QueryConstructor;\n  {s}Mutable: {s}MutableConstructor;\n", .{
